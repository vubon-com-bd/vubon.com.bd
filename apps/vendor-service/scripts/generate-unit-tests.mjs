// ─────────────────────────────────────────────
// Pascal case helper
// ─────────────────────────────────────────────
function pascalCase(str) {
  return str
    .split('-')
    .map((s) => s.charAt(0).toUpperCase() + s.slice(1))
    .join('');
}

// ─────────────────────────────────────────────
// Class name derivation
// ─────────────────────────────────────────────
function voClassName(base) {
  // vendor-id → VendorIdVO
  return pascalCase(base) + 'VO';
}

function entityClassName(base) {
  // vendor → VendorEntity
  return pascalCase(base) + 'Entity';
}

function serviceClassName(base) {
  // vendor-eligibility → VendorEligibilityService
  return pascalCase(base) + 'Service';
}

// ─────────────────────────────────────────────
// Main
// ─────────────────────────────────────────────
function main() {
  console.log('📦 Generating unit test scaffolds...\n');

  let created = 0;

  // ─── VOs ───
  const voDir = join(SRC, 'domain', 'value-objects', 'primitives');
  const voTestDir = join(TEST, 'domain', 'value-objects');
  if (!existsSync(voTestDir)) mkdirSync(voTestDir, { recursive: true });

  if (existsSync(voDir)) {
    const voFiles = readdirSync(voDir).filter((f) => f.endsWith('.vo.ts'));
    console.log(`─── VOs (${voFiles.length}) ───`);
    for (const f of voFiles) {
      const name = basename(f, '.vo.ts');
      const className = voClassName(name);
      const target = join(voTestDir, `${name}.vo.spec.ts`);
      if (existsSync(target)) {
        console.log(`  ⏭️  ${name}.vo.spec.ts (exists)`);
        continue;
      }
      writeFileSync(target, voSpec(name, className), 'utf8');
      console.log(`  ✅ ${name}.vo.spec.ts`);
      created++;
    }
  }

  // ─── Entities ───
  const entityDir = join(SRC, 'domain', 'entities');
  const entityTestDir = join(TEST, 'domain', 'entities');
  if (!existsSync(entityTestDir)) mkdirSync(entityTestDir, { recursive: true });

  if (existsSync(entityDir)) {
    const entityFiles = readdirSync(entityDir).filter((f) => f.endsWith('.entity.ts'));
    console.log(`\n─── Entities (${entityFiles.length}) ───`);
    for (const f of entityFiles) {
      const name = basename(f, '.entity.ts');
      const className = entityClassName(name);
      const target = join(entityTestDir, `${name}.entity.spec.ts`);
      if (existsSync(target)) {
        console.log(`  ⏭️  ${name}.entity.spec.ts (exists)`);
        continue;
      }
      writeFileSync(target, entitySpec(name, className), 'utf8');
      console.log(`  ✅ ${name}.entity.spec.ts`);
      created++;
    }
  }

  // ─── Domain Services ───
  const svcDir = join(SRC, 'domain', 'services');
  const svcTestDir = join(TEST, 'domain', 'services');
  if (!existsSync(svcTestDir)) mkdirSync(svcTestDir, { recursive: true });

  if (existsSync(svcDir)) {
    const svcFiles = readdirSync(svcDir).filter((f) => f.endsWith('.service.ts'));
    console.log(`\n─── Domain Services (${svcFiles.length}) ───`);
    for (const f of svcFiles) {
      const name = basename(f, '.service.ts');
      const className = serviceClassName(name);
      const target = join(svcTestDir, `${name}.service.spec.ts`);
      if (existsSync(target)) {
        console.log(`  ⏭️  ${name}.service.spec.ts (exists)`);
        continue;
      }
      writeFileSync(target, serviceSpec(name, className), 'utf8');
      console.log(`  ✅ ${name}.service.spec.ts`);
      created++;
    }
  }

  console.log(`\n📊 Summary: ${created} new spec file(s) generated`);
  console.log(`📁 Output: ${TEST}`);
}

main();
