/**
 * InvoiceService
 * @module payment-service/application/services/impl
 */
import { Inject, Injectable, Logger } from '@nestjs/common';
import { randomUUID } from 'node:crypto';

import type {
  IInvoiceService,
  InvoiceListOptionsDTO,
} from '@application/services/interfaces/invoice.service.interface.js';
import {
  INVOICE_REPOSITORY,
  type InvoiceRepository,
} from '@domain/repositories/invoice.repository.interface.js';
import { InvoiceEntity } from '@domain/entities/invoice.entity.js';
import { InvoiceIdVO } from '@domain/primitives/invoice-id.vo';
import { InvoiceNumberVO } from '@domain/primitives/invoice-number.vo';
import { InvoiceAmountVO } from '@domain/primitives/invoice-amount.vo';
import { UserIdVO } from '@domain/primitives/user-id.vo';
import { OrderIdVO } from '@domain/primitives/order-id.vo';
import { InvoiceNumberService } from '@domain/services/invoice-number.service.js';

import type {
  GenerateInvoiceRequestDTO,
  SendInvoiceRequestDTO,
  VoidInvoiceRequestDTO,
} from '@application/dtos/requests/invoice/index.js';
import type {
  InvoiceResponseDTO,
  InvoiceListResponseDTO,
  InvoiceStatsResponseDTO,
} from '@application/dtos/responses/invoice-response.dto.js';
import {
  InvoiceNotFoundApplicationError,
  InvoiceGenerationError,
  InvoiceSendError,
  InvoiceVoidError,
} from '@application/errors/invoice.errors.js';

@Injectable()
export class InvoiceService implements IInvoiceService {
  private readonly logger = new Logger(InvoiceService.name);

  constructor(
    @Inject(INVOICE_REPOSITORY)
    private readonly repo: InvoiceRepository,
  ) {}

  async generate(
    dto: GenerateInvoiceRequestDTO,
    actorId?: string,
  ): Promise<InvoiceResponseDTO> {
    try {
      const now = new Date().toISOString();
      const id = randomUUID();
      const invoiceNumber = InvoiceNumberService.generate();
      const entity = InvoiceEntity.create({
        id: InvoiceIdVO.create(id),
        now,
        props: {
          invoiceNumber: InvoiceNumberVO.create(invoiceNumber),
          amount: InvoiceAmountVO.create(dto.subtotal, dto.taxAmount, dto.currency),
          userId: UserIdVO.create(dto.userId),
          orderId: dto.orderId ? OrderIdVO.create(dto.orderId) : undefined,
          dueAt: dto.dueAt,
          notes: dto.notes,
        },
      });
      entity.issue();
      const saved = await this.repo.save(entity);
      this.logger.log(`Invoice ${saved.id} (${invoiceNumber}) generated by ${actorId ?? 'system'}`);
      return this.toResponse(saved);
    } catch (e) {
      const msg = e instanceof Error ? e.message : 'Unknown';
      throw new InvoiceGenerationError(dto.orderId ?? 'no-order', msg);
    }
  }

  async send(dto: SendInvoiceRequestDTO, actorId?: string): Promise<InvoiceResponseDTO> {
    try {
      const entity = await this.load(dto.invoiceId);
      this.logger.log(
        `Invoice ${entity.id} sent via ${dto.channel} by ${actorId ?? 'system'}`,
      );
      return this.toResponse(entity);
    } catch (e) {
      if (e instanceof InvoiceNotFoundApplicationError) throw e;
      const msg = e instanceof Error ? e.message : 'Unknown';
      throw new InvoiceSendError(dto.invoiceId, msg);
    }
  }

  async void(dto: VoidInvoiceRequestDTO, actorId?: string): Promise<InvoiceResponseDTO> {
    try {
      const entity = await this.load(dto.invoiceId);
      entity.void();
      const saved = await this.repo.save(entity);
      this.logger.log(`Invoice ${saved.id} voided by ${actorId ?? 'system'}`);
      return this.toResponse(saved);
    } catch (e) {
      if (e instanceof InvoiceNotFoundApplicationError) throw e;
      const msg = e instanceof Error ? e.message : 'Unknown';
      throw new InvoiceVoidError(dto.invoiceId, msg);
    }
  }

  async getById(id: string): Promise<InvoiceResponseDTO> {
    return this.toResponse(await this.load(id));
  }

  async listByUser(userId: string): Promise<readonly InvoiceResponseDTO[]> {
    const entities = await this.repo.findByUser(userId);
    return entities.map((e) => this.toResponse(e));
  }

  async list(options: InvoiceListOptionsDTO): Promise<InvoiceListResponseDTO> {
    const result = await this.repo.findPaginated({
      page: options.page,
      limit: options.limit,
      sortBy: options.sortBy,
      sortDir: options.sortDir,
      filter: options.filter,
    });
    return {
      items: result.items.map((e) => ({
        id: e.id,
        invoiceNumber: e.invoiceNumber.value,
        status: e.status.value,
        total: e.amount.total,
        currency: e.amount.currency,
        dueAt: e.dueAt,
      })),
      total: result.total,
      page: result.page,
      limit: result.limit,
      totalPages: result.totalPages,
    };
  }

  async getStats(userId?: string): Promise<InvoiceStatsResponseDTO> {
    const stats = await this.repo.getStats(userId);
    return {
      total: stats.total,
      totalAmount: stats.totalAmount,
      outstandingAmount: stats.outstandingAmount,
      currency: stats.currency,
      byStatus: stats.byStatus,
    };
  }

  private async load(id: string): Promise<InvoiceEntity> {
    const vo = InvoiceIdVO.create(id);
    const entity = await this.repo.findByIdVO(vo);
    if (!entity) throw new InvoiceNotFoundApplicationError(id);
    return entity;
  }

  private toResponse(e: InvoiceEntity): InvoiceResponseDTO {
    return {
      id: e.id,
      invoiceNumber: e.invoiceNumber.value,
      userId: e.userId.value,
      orderId: e.orderId?.value,
      status: e.status.value,
      subtotal: e.amount.subtotal,
      taxAmount: e.amount.taxAmount,
      total: e.amount.total,
      currency: e.amount.currency,
      issuedAt: e.issuedAt,
      dueAt: e.dueAt,
      paidAt: e.paidAt,
      voidedAt: e.voidedAt,
      refundedAt: e.refundedAt,
      notes: e.notes,
      createdAt: e.createdAt,
      updatedAt: e.updatedAt,
    };
  }
}
