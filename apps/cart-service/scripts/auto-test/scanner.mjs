/**
 * Auto Test Scanner — Uses TypeScript Compiler API
 * @module cart-service/scripts/auto-test
 */

import { Project } from 'ts-morph';
import { join, relative } from 'node:path';

export function scanDirectory(rootDir, patterns) {
  const project = new Project({
    tsConfigFilePath: join(rootDir, 'tsconfig.json'),
    skipAddingFilesFromTsConfig: true,
  });

  for (const pattern of patterns) {
    project.addSourceFilesAtPaths(join(rootDir, pattern));
  }

  const sourceFiles = project.getSourceFiles();
  const units = [];

  for (const sourceFile of sourceFiles) {
    const filePath = sourceFile.getFilePath();

    if (
      filePath.endsWith('index.ts') ||
      filePath.endsWith('.interface.ts') ||
      filePath.endsWith('.dto.ts') ||
      filePath.endsWith('.types.ts') ||
      filePath.endsWith('.errors.ts')
    ) {
      continue;
    }

    const classes = sourceFile.getClasses();

    for (const classDecl of classes) {
      const className = classDecl.getName();
      if (!className) continue;
      if (classDecl.isAbstract()) continue;

      const methods = classDecl.getMethods();

      // Filter public methods — use getScope() instead of isPrivate()
      const publicMethods = methods.filter((m) => {
        const scope = m.getScope();
        return scope !== 'private' && scope !== 'protected';
      });

      if (publicMethods.length === 0) continue;

      const isStatic = publicMethods.every((m) => m.isStatic());

      const relativePath = relative(join(rootDir, 'src/module'), filePath)
        .replace(/\\/g, '/')
        .replace(/\.ts$/, '');

      const scenarios = [];

      for (const method of publicMethods) {
        if (method.getName() === 'constructor') continue;

        const methodName = method.getName();
        const returnType = method.getReturnType().getText();
        const isPromise = returnType.startsWith('Promise');
        const isVoid = returnType === 'void' || returnType === 'Promise<void>';

        scenarios.push({
          name: `should invoke ${methodName}`,
          varName: 'result',
          async: isPromise,
          isStatic,
          call: isStatic
            ? `${className}.${methodName}()`
            : `(() => {
              try {
                const instance = new ${className}({} as never);
                return instance.${methodName}();
              } catch {
                return undefined;
              }
            })()`,
          expect: isVoid || isPromise
            ? `expect(result).toBeDefined();`
            : `expect(result).toBeDefined();`,
        });
      }

      units.push({
        group: deriveGroup(relativePath),
        type: isStatic ? 'static' : 'instance',
        path: relativePath,
        className,
        scenarios,
        autoGenerated: true,
      });
    }
  }

  return units;
}

function deriveGroup(relativePath) {
  if (relativePath.includes('value-objects/primitives')) return 'vo-primitives';
  if (relativePath.includes('value-objects/composites')) return 'vo-composites';
  if (relativePath.includes('domain/services')) return 'domain-services';
  if (relativePath.includes('domain/specifications')) return 'specifications';
  if (relativePath.includes('domain/entities')) return 'entities';
  if (relativePath.includes('domain/events')) return 'events';
  if (relativePath.includes('application/services/impl')) return 'app-services';
  if (relativePath.includes('application/mappers')) return 'mappers';
  return 'other';
}

export function summarize(units) {
  const stats = {
    totalUnits: units.length,
    totalScenarios: 0,
    byGroup: {},
  };

  for (const unit of units) {
    stats.totalScenarios += unit.scenarios.length;
    if (!stats.byGroup[unit.group]) {
      stats.byGroup[unit.group] = { units: 0, scenarios: 0 };
    }
    stats.byGroup[unit.group].units += 1;
    stats.byGroup[unit.group].scenarios += unit.scenarios.length;
  }

  return stats;
}
