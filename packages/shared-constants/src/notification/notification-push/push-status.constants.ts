export function notificationpushIsDelivered(status: NotificationPushStatusType): boolean {
  const deliveredStatuses: NotificationPushStatusType[] = [
    NOTIFICATIONPUSH_STATUS.STATUSES.DELIVERED,
    NOTIFICATIONPUSH_STATUS.STATUSES.OPENED,
    NOTIFICATIONPUSH_STATUS.STATUSES.CLICKED,
  ];
  return deliveredStatuses.includes(status);
}

