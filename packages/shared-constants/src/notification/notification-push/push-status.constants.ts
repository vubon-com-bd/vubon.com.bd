export function notificationpushCanTransition(
  currentStatus: NotificationPushStatusType,
  targetStatus: NotificationPushStatusType
): boolean {
  const validTransitions: Record<NotificationPushStatusType, NotificationPushStatusType[]> = {
    [NOTIFICATIONPUSH_STATUS.STATUSES.DRAFT]: [
      NOTIFICATIONPUSH_STATUS.STATUSES.PENDING,
      NOTIFICATIONPUSH_STATUS.STATUSES.CANCELLED,
      NOTIFICATIONPUSH_STATUS.STATUSES.ARCHIVED,
    ],
    [NOTIFICATIONPUSH_STATUS.STATUSES.PENDING]: [
      NOTIFICATIONPUSH_STATUS.STATUSES.SCHEDULED,
      NOTIFICATIONPUSH_STATUS.STATUSES.QUEUED,
      NOTIFICATIONPUSH_STATUS.STATUSES.CANCELLED,
    ],
    [NOTIFICATIONPUSH_STATUS.STATUSES.SCHEDULED]: [
      NOTIFICATIONPUSH_STATUS.STATUSES.QUEUED,
      NOTIFICATIONPUSH_STATUS.STATUSES.CANCELLED,
    ],
    [NOTIFICATIONPUSH_STATUS.STATUSES.QUEUED]: [
      NOTIFICATIONPUSH_STATUS.STATUSES.PROCESSING,
      NOTIFICATIONPUSH_STATUS.STATUSES.CANCELLED,
    ],
    [NOTIFICATIONPUSH_STATUS.STATUSES.PROCESSING]: [
      NOTIFICATIONPUSH_STATUS.STATUSES.SENT,
      NOTIFICATIONPUSH_STATUS.STATUSES.FAILED,
      NOTIFICATIONPUSH_STATUS.STATUSES.CANCELLED,
    ],
    [NOTIFICATIONPUSH_STATUS.STATUSES.SENT]: [
      NOTIFICATIONPUSH_STATUS.STATUSES.DELIVERED,
      NOTIFICATIONPUSH_STATUS.STATUSES.FAILED,
      NOTIFICATIONPUSH_STATUS.STATUSES.REJECTED,
    ],
    [NOTIFICATIONPUSH_STATUS.STATUSES.DELIVERED]: [
      NOTIFICATIONPUSH_STATUS.STATUSES.OPENED,
      NOTIFICATIONPUSH_STATUS.STATUSES.DISMISSED,
      NOTIFICATIONPUSH_STATUS.STATUSES.FAILED,
    ],
    [NOTIFICATIONPUSH_STATUS.STATUSES.OPENED]: [
      NOTIFICATIONPUSH_STATUS.STATUSES.CLICKED,
      NOTIFICATIONPUSH_STATUS.STATUSES.DISMISSED,
      NOTIFICATIONPUSH_STATUS.STATUSES.ARCHIVED,
    ],
    [NOTIFICATIONPUSH_STATUS.STATUSES.CLICKED]: [NOTIFICATIONPUSH_STATUS.STATUSES.ARCHIVED],
    [NOTIFICATIONPUSH_STATUS.STATUSES.DISMISSED]: [NOTIFICATIONPUSH_STATUS.STATUSES.ARCHIVED],
    [NOTIFICATIONPUSH_STATUS.STATUSES.FAILED]: [NOTIFICATIONPUSH_STATUS.STATUSES.ARCHIVED],
    [NOTIFICATIONPUSH_STATUS.STATUSES.REJECTED]: [NOTIFICATIONPUSH_STATUS.STATUSES.ARCHIVED],
    [NOTIFICATIONPUSH_STATUS.STATUSES.CANCELLED]: [NOTIFICATIONPUSH_STATUS.STATUSES.ARCHIVED],
    [NOTIFICATIONPUSH_STATUS.STATUSES.EXPIRED]: [NOTIFICATIONPUSH_STATUS.STATUSES.ARCHIVED],
    [NOTIFICATIONPUSH_STATUS.STATUSES.ARCHIVED]: [],
  };

  return validTransitions[currentStatus]?.includes(targetStatus) || false;
}
