    [NOTIFICATIONPREFERENCE_STATUS.STATUSES.REJECTED]: 'Rejected',
    [NOTIFICATIONPREFERENCE_STATUS.STATUSES.ARCHIVED]: 'Archived',
    [NOTIFICATIONPREFERENCE_STATUS.STATUSES.DRAFT]: 'Draft',
    [NOTIFICATIONPREFERENCE_STATUS.STATUSES.SUSPENDED]: 'Suspended',
