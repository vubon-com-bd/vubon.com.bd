export function notificationpreferenceIsActive(status: NotificationPreferenceStatusType): boolean {
  const activeStatuses: NotificationPreferenceStatusType[] = [
    NOTIFICATIONPREFERENCE_STATUS.STATUSES.ACTIVE,
    NOTIFICATIONPREFERENCE_STATUS.STATUSES.INHERITED,
  ];
  return activeStatuses.includes(status);
}

export function notificationpreferenceIsPending(status: NotificationPreferenceStatusType): boolean {
  const pendingStatuses: NotificationPreferenceStatusType[] = [
    NOTIFICATIONPREFERENCE_STATUS.STATUSES.PENDING,
    NOTIFICATIONPREFERENCE_STATUS.STATUSES.APPROVED,
    NOTIFICATIONPREFERENCE_STATUS.STATUSES.DRAFT,
  ];
  return pendingStatuses.includes(status);
}

export function notificationpreferenceIsInactive(
  status: NotificationPreferenceStatusType
): boolean {
  const inactiveStatuses: NotificationPreferenceStatusType[] = [
    NOTIFICATIONPREFERENCE_STATUS.STATUSES.INACTIVE,
    NOTIFICATIONPREFERENCE_STATUS.STATUSES.SUSPENDED,
    NOTIFICATIONPREFERENCE_STATUS.STATUSES.EXPIRED,
  ];
  return inactiveStatuses.includes(status);
}

export function notificationpreferenceIsOverridden(
  status: NotificationPreferenceStatusType
): boolean {
  return status === NOTIFICATIONPREFERENCE_STATUS.STATUSES.OVERRIDDEN;
}

