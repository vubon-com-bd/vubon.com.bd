export function notificationIsMarketingCategory(category: NotificationCategoryType): boolean {
  const marketingCategories: NotificationCategoryType[] = [
    NOTIFICATION_CATEGORY.CATEGORIES.MARKETING,
    NOTIFICATION_CATEGORY.CATEGORIES.PROMOTIONAL,
    NOTIFICATION_CATEGORY.CATEGORIES.EDUCATIONAL,
  ];
  return marketingCategories.includes(category);
}

export function notificationIsTransactionalCategory(category: NotificationCategoryType): boolean {
  const transactionalCategories: NotificationCategoryType[] = [
    NOTIFICATION_CATEGORY.CATEGORIES.TRANSACTIONAL,
    NOTIFICATION_CATEGORY.CATEGORIES.SECURITY,
    NOTIFICATION_CATEGORY.CATEGORIES.OPERATIONAL,
  ];
  return transactionalCategories.includes(category);
}

export function notificationIsSystemCategory(category: NotificationCategoryType): boolean {
  const systemCategories: NotificationCategoryType[] = [
    NOTIFICATION_CATEGORY.CATEGORIES.SYSTEM,
    NOTIFICATION_CATEGORY.CATEGORIES.ALERT,
  ];
  return systemCategories.includes(category);
}

export function notificationIsSocialCategory(category: NotificationCategoryType): boolean {
  const socialCategories: NotificationCategoryType[] = [
    NOTIFICATION_CATEGORY.CATEGORIES.SOCIAL,
    NOTIFICATION_CATEGORY.CATEGORIES.COMMUNITY,
  ];
  return socialCategories.includes(category);
}

