export function notificationdeviceIsPending(status: NotificationDeviceStatusType): boolean {
  const pendingStatuses: NotificationDeviceStatusType[] = [
    NOTIFICATIONDEVICE_STATUS.STATUSES.PENDING,
    NOTIFICATIONDEVICE_STATUS.STATUSES.REGISTERED,
    NOTIFICATIONDEVICE_STATUS.STATUSES.UNVERIFIED,
    NOTIFICATIONDEVICE_STATUS.STATUSES.APPROVED,
  ];
  return pendingStatuses.includes(status);
}

