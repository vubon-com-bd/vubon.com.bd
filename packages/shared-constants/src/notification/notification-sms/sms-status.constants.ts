export function notificationsmsIsDelivered(status: NotificationSMSStatusType): boolean {
  return status === NOTIFICATIONSMS_STATUS.STATUSES.DELIVERED;
}

export function notificationsmsIsSent(status: NotificationSMSStatusType): boolean {
  const sentStatuses: NotificationSMSStatusType[] = [
    NOTIFICATIONSMS_STATUS.STATUSES.SENT,
    NOTIFICATIONSMS_STATUS.STATUSES.DELIVERED,
    NOTIFICATIONSMS_STATUS.STATUSES.DEFERRED,
  ];
  return sentStatuses.includes(status);
}

export function notificationsmsIsFailed(status: NotificationSMSStatusType): boolean {
  const failedStatuses: NotificationSMSStatusType[] = [
    NOTIFICATIONSMS_STATUS.STATUSES.FAILED,
    NOTIFICATIONSMS_STATUS.STATUSES.UNDELIVERED,
    NOTIFICATIONSMS_STATUS.STATUSES.REJECTED,
    NOTIFICATIONSMS_STATUS.STATUSES.BOUNCED,
    NOTIFICATIONSMS_STATUS.STATUSES.SPAM,
    NOTIFICATIONSMS_STATUS.STATUSES.EXPIRED,
  ];
  return failedStatuses.includes(status);
}

export function notificationsmsIsPending(status: NotificationSMSStatusType): boolean {
  const pendingStatuses: NotificationSMSStatusType[] = [
    NOTIFICATIONSMS_STATUS.STATUSES.PENDING,
    NOTIFICATIONSMS_STATUS.STATUSES.QUEUED,
    NOTIFICATIONSMS_STATUS.STATUSES.PROCESSING,
    NOTIFICATIONSMS_STATUS.STATUSES.SENT,
    NOTIFICATIONSMS_STATUS.STATUSES.DEFERRED,
  ];
  return pendingStatuses.includes(status);
}

export function notificationsmsCanTransition(
  currentStatus: NotificationSMSStatusType,
  targetStatus: NotificationSMSStatusType
): boolean {
  const validTransitions: Record<NotificationSMSStatusType, NotificationSMSStatusType[]> = {
    [NOTIFICATIONSMS_STATUS.STATUSES.DRAFT]: [
      NOTIFICATIONSMS_STATUS.STATUSES.PENDING,
      NOTIFICATIONSMS_STATUS.STATUSES.CANCELLED,
      NOTIFICATIONSMS_STATUS.STATUSES.ARCHIVED,
    ],
    [NOTIFICATIONSMS_STATUS.STATUSES.PENDING]: [
      NOTIFICATIONSMS_STATUS.STATUSES.QUEUED,
      NOTIFICATIONSMS_STATUS.STATUSES.CANCELLED,
    ],
    [NOTIFICATIONSMS_STATUS.STATUSES.QUEUED]: [
      NOTIFICATIONSMS_STATUS.STATUSES.PROCESSING,
      NOTIFICATIONSMS_STATUS.STATUSES.CANCELLED,
    ],
    [NOTIFICATIONSMS_STATUS.STATUSES.PROCESSING]: [
      NOTIFICATIONSMS_STATUS.STATUSES.SENT,
      NOTIFICATIONSMS_STATUS.STATUSES.FAILED,
      NOTIFICATIONSMS_STATUS.STATUSES.CANCELLED,
    ],
    [NOTIFICATIONSMS_STATUS.STATUSES.SENT]: [
      NOTIFICATIONSMS_STATUS.STATUSES.DELIVERED,
      NOTIFICATIONSMS_STATUS.STATUSES.UNDELIVERED,
      NOTIFICATIONSMS_STATUS.STATUSES.FAILED,
      NOTIFICATIONSMS_STATUS.STATUSES.DEFERRED,
      NOTIFICATIONSMS_STATUS.STATUSES.BOUNCED,
    ],
    [NOTIFICATIONSMS_STATUS.STATUSES.DEFERRED]: [
      NOTIFICATIONSMS_STATUS.STATUSES.SENT,
      NOTIFICATIONSMS_STATUS.STATUSES.FAILED,
      NOTIFICATIONSMS_STATUS.STATUSES.CANCELLED,
    ],
    [NOTIFICATIONSMS_STATUS.STATUSES.DELIVERED]: [
      NOTIFICATIONSMS_STATUS.STATUSES.OPT_OUT,
      NOTIFICATIONSMS_STATUS.STATUSES.SPAM,
    ],
    [NOTIFICATIONSMS_STATUS.STATUSES.UNDELIVERED]: [NOTIFICATIONSMS_STATUS.STATUSES.ARCHIVED],
    [NOTIFICATIONSMS_STATUS.STATUSES.FAILED]: [NOTIFICATIONSMS_STATUS.STATUSES.ARCHIVED],
    [NOTIFICATIONSMS_STATUS.STATUSES.REJECTED]: [NOTIFICATIONSMS_STATUS.STATUSES.ARCHIVED],
    [NOTIFICATIONSMS_STATUS.STATUSES.BOUNCED]: [NOTIFICATIONSMS_STATUS.STATUSES.ARCHIVED],
    [NOTIFICATIONSMS_STATUS.STATUSES.EXPIRED]: [NOTIFICATIONSMS_STATUS.STATUSES.ARCHIVED],
    [NOTIFICATIONSMS_STATUS.STATUSES.OPT_OUT]: [NOTIFICATIONSMS_STATUS.STATUSES.ARCHIVED],
    [NOTIFICATIONSMS_STATUS.STATUSES.SPAM]: [NOTIFICATIONSMS_STATUS.STATUSES.ARCHIVED],
    [NOTIFICATIONSMS_STATUS.STATUSES.CANCELLED]: [NOTIFICATIONSMS_STATUS.STATUSES.ARCHIVED],
    [NOTIFICATIONSMS_STATUS.STATUSES.ARCHIVED]: [],
  };

  return validTransitions[currentStatus]?.includes(targetStatus) || false;
}
