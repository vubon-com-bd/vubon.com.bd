export function notificationIsDeliveredStatus(status: NotificationDeliveryStatusType): boolean {
  const deliveredStatuses: NotificationDeliveryStatusType[] = [
    NOTIFICATION_DELIVERY_STATUS.STATUSES.DELIVERED,
    NOTIFICATION_DELIVERY_STATUS.STATUSES.OPENED,
    NOTIFICATION_DELIVERY_STATUS.STATUSES.CLICKED,
  ];
  return deliveredStatuses.includes(status);
}

export function notificationIsBouncedStatus(status: NotificationDeliveryStatusType): boolean {
  const bouncedStatuses: NotificationDeliveryStatusType[] = [
    NOTIFICATION_DELIVERY_STATUS.STATUSES.BOUNCED,
    NOTIFICATION_DELIVERY_STATUS.STATUSES.SOFT_BOUNCE,
    NOTIFICATION_DELIVERY_STATUS.STATUSES.HARD_BOUNCE,
  ];
  return bouncedStatuses.includes(status);
}

