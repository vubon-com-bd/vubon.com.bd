export function notificationruleIsActive(status: NotificationRuleStatusType): boolean {
  const activeStatuses: NotificationRuleStatusType[] = [
    NOTIFICATIONRULE_STATUS.STATUSES.ACTIVE,
    NOTIFICATIONRULE_STATUS.STATUSES.DEPLOYED,
  ];
  return activeStatuses.includes(status);
}

export function notificationruleIsPending(status: NotificationRuleStatusType): boolean {
  const pendingStatuses: NotificationRuleStatusType[] = [
    NOTIFICATIONRULE_STATUS.STATUSES.PENDING,
    NOTIFICATIONRULE_STATUS.STATUSES.UNDER_REVIEW,
    NOTIFICATIONRULE_STATUS.STATUSES.APPROVED,
    NOTIFICATIONRULE_STATUS.STATUSES.TESTING,
  ];
  return pendingStatuses.includes(status);
}

