/**
 * স্কোর থেকে ডিফিকাল্টি লেভেল নির্ধারণ
 */
export const getKeywordDifficultyLevel = (score: number): SEOKeywordDifficultyLevel => {
  if (score >= SEO_KEYWORD_DIFFICULTY_THRESHOLDS[SEO_KEYWORD_DIFFICULTY_LEVEL.EXTREME]) {
    return SEO_KEYWORD_DIFFICULTY_LEVEL.EXTREME;
  }
  if (score >= SEO_KEYWORD_DIFFICULTY_THRESHOLDS[SEO_KEYWORD_DIFFICULTY_LEVEL.VERY_HARD]) {
    return SEO_KEYWORD_DIFFICULTY_LEVEL.VERY_HARD;
  }
  if (score >= SEO_KEYWORD_DIFFICULTY_THRESHOLDS[SEO_KEYWORD_DIFFICULTY_LEVEL.HARD]) {
    return SEO_KEYWORD_DIFFICULTY_LEVEL.HARD;
  }
  if (score >= SEO_KEYWORD_DIFFICULTY_THRESHOLDS[SEO_KEYWORD_DIFFICULTY_LEVEL.MODERATE]) {
    return SEO_KEYWORD_DIFFICULTY_LEVEL.MODERATE;
  }
  if (score >= SEO_KEYWORD_DIFFICULTY_THRESHOLDS[SEO_KEYWORD_DIFFICULTY_LEVEL.EASY]) {
    return SEO_KEYWORD_DIFFICULTY_LEVEL.EASY;
  }
  return SEO_KEYWORD_DIFFICULTY_LEVEL.VERY_EASY;
};

