export function logisticsDeliveryIsDelivered(status: LogisticsDeliveryStatus): boolean {
  return status === LOGISTICS_DELIVERY.STATUS.DELIVERED;
}

export function logisticsDeliveryIsInTransit(status: LogisticsDeliveryStatus): boolean {
  const transitStatuses: LogisticsDeliveryStatus[] = [
    LOGISTICS_DELIVERY.STATUS.PICKED_UP,
    LOGISTICS_DELIVERY.STATUS.IN_TRANSIT,
    LOGISTICS_DELIVERY.STATUS.OUT_FOR_DELIVERY,
  ];
  return transitStatuses.includes(status);
}

export function logisticsDeliveryIsFailed(status: LogisticsDeliveryStatus): boolean {
  return (
    status === LOGISTICS_DELIVERY.STATUS.FAILED ||
    status === LOGISTICS_DELIVERY.STATUS.RETURNED ||
    status === LOGISTICS_DELIVERY.STATUS.CANCELLED
  );
}

export function logisticsDeliveryGetCODFreeAmount(): number {
  return LOGISTICS_DELIVERY.COD.FREE_ABOVE;
}

export function logisticsDeliveryIsCODFree(amount: number): boolean {
  return amount >= LOGISTICS_DELIVERY.COD.FREE_ABOVE;
}

export function logisticsDeliveryGetCODCharge(amount: number): number {
  if (logisticsDeliveryIsCODFree(amount)) {
    return 0;
  }
  const percentageCharge = amount * LOGISTICS_DELIVERY.COD.PERCENTAGE;
  return Math.max(LOGISTICS_DELIVERY.COD.CHARGE, percentageCharge);
}
