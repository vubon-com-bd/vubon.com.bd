export function marketingleadIsQualified(status: MarketingLeadStatusType): boolean {
  const qualifiedStatuses: MarketingLeadStatusType[] = [
    MARKETINGLEAD_STATUS.STATUSES.QUALIFIED,
    MARKETINGLEAD_STATUS.STATUSES.CONVERTED,
    MARKETINGLEAD_STATUS.STATUSES.IN_PROGRESS,
  ];
  return qualifiedStatuses.includes(status);
}

export function marketingleadIsActive(status: MarketingLeadStatusType): boolean {
  const activeStatuses: MarketingLeadStatusType[] = [
    MARKETINGLEAD_STATUS.STATUSES.NEW,
    MARKETINGLEAD_STATUS.STATUSES.CONTACTED,
    MARKETINGLEAD_STATUS.STATUSES.ENGAGED,
    MARKETINGLEAD_STATUS.STATUSES.NURTURING,
    MARKETINGLEAD_STATUS.STATUSES.FOLLOW_UP,
    MARKETINGLEAD_STATUS.STATUSES.WAITING,
    MARKETINGLEAD_STATUS.STATUSES.IN_PROGRESS,
  ];
  return activeStatuses.includes(status);
}

export function marketingleadIsLost(status: MarketingLeadStatusType): boolean {
  const lostStatuses: MarketingLeadStatusType[] = [
    MARKETINGLEAD_STATUS.STATUSES.LOST,
    MARKETINGLEAD_STATUS.STATUSES.DISQUALIFIED,
    MARKETINGLEAD_STATUS.STATUSES.REJECTED,
  ];
  return lostStatuses.includes(status);
}

