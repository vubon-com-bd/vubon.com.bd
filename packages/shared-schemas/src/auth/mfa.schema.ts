/**
 * MFA validation utilities
 */
export const MFAValidator = {
  /**
   * Validate an enable MFA request
   */
  validateEnable: (data: unknown) => EnableMFASchema.safeParse(data),

  /**
   * Validate a verify MFA request
   */
  validateVerify: (data: unknown) => VerifyMFASchema.safeParse(data),

  /**
   * Validate a disable MFA request
   */
  validateDisable: (data: unknown) => DisableMFASchema.safeParse(data),

  /**
   * Validate a generate backup codes request
   */
  validateGenerateBackupCodes: (data: unknown) => GenerateBackupCodesSchema.safeParse(data),

  /**
   * Validate an MFA challenge request
   */
  validateChallenge: (data: unknown) => MFAChallengeRequestSchema.safeParse(data),

  /**
   * Validate an MFA trust device request
   */
  validateTrustDevice: (data: unknown) => MFATrustDeviceSchema.safeParse(data),

  /**
   * Validate an MFA recovery request
   */
  validateRecovery: (data: unknown) => MFARecoveryRequestSchema.safeParse(data),

  /**
   * Validate and throw for enable MFA
   */
  validateEnableOrThrow: (data: unknown) => EnableMFASchema.parse(data),

  /**
   * Validate and throw for verify MFA
   */
  validateVerifyOrThrow: (data: unknown) => VerifyMFASchema.parse(data),

  /**
   * Validate and throw for disable MFA
   */
  validateDisableOrThrow: (data: unknown) => DisableMFASchema.parse(data),

  /**
   * Validate and throw for generate backup codes
   */
  validateGenerateBackupCodesOrThrow: (data: unknown) => GenerateBackupCodesSchema.parse(data),

  /**
   * Validate and throw for MFA challenge
   */
  validateChallengeOrThrow: (data: unknown) => MFAChallengeRequestSchema.parse(data),

  /**
   * Validate and throw for trust device
   */
  validateTrustDeviceOrThrow: (data: unknown) => MFATrustDeviceSchema.parse(data),

  /**
   * Validate and throw for recovery
   */
  validateRecoveryOrThrow: (data: unknown) => MFARecoveryRequestSchema.parse(data),
};

