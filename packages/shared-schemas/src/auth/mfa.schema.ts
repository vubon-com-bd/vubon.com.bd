import { z } from 'zod';

/**
 * MFA type enum
 * Currently only TOTP is supported
 */
export const MFATypeSchema = z.enum(['totp']);

/**
 * MFA method type enum
 * Supported MFA methods
 */
export const MFAMethodSchema = z.enum(['authenticator', 'sms', 'email', 'backup_codes']);

/**
 * Enable MFA schema
 * Used when enabling MFA for a user
 */
export const EnableMFASchema = z.object({
  /**
   * Type of MFA to enable
   * Currently only 'totp' is supported
   */
  type: z.enum(['totp']),

  /**
   * Phone number for SMS (required if type is sms)
   */
  phoneNumber: z
    .string()
    .regex(/^(?:\+8801|01)[3-9]\d{8}$/, 'Please provide a valid Bangladeshi phone number')
    .optional(),

  /**
   * Email address for email (required if type is email)
   */
  email: z.string().email('Please provide a valid email address').optional(),

  /**
   * TOTP secret (generated by server)
   */
  secret: z.string().min(16, 'Invalid TOTP secret').optional(),

  /**
   * Device name for the MFA method
   */
  deviceName: z.string().max(50, 'Device name must not exceed 50 characters').optional(),
});

/**
 * Verify MFA schema
 * Used when verifying an MFA code
 */
export const VerifyMFASchema = z.object({
  /**
   * MFA code to verify
   * - Must be exactly 6 digits
   */
  code: z
    .string()
    .length(6, 'MFA code must be exactly 6 digits')
    .regex(/^\d{6}$/, 'MFA code must contain only numbers'),

  /**
   * Method ID for specific method (optional)
   */
  methodId: z.string().uuid('Invalid method ID format').optional(),

  /**
   * Type of MFA method (optional)
   */
  type: z.enum(['totp', 'sms', 'email', 'backup_codes']).optional(),

  /**
   * Trust this device after verification
   */
  trustDevice: z.boolean().optional().default(false),

  /**
   * Device name (if trusting device)
   */
  deviceName: z.string().max(50, 'Device name must not exceed 50 characters').optional(),
});

/**
 * Disable MFA schema
 * Used when disabling MFA for a user
 * Either code or backupCode is required
 */
export const DisableMFASchema = z
  .object({
    /**
     * MFA code for verification
     */
    code: z
      .string()
      .length(6, 'MFA code must be exactly 6 digits')
      .regex(/^\d{6}$/, 'MFA code must contain only numbers')
      .optional(),

    /**
     * Backup code for verification
     */
    backupCode: z
      .string()
      .length(8, 'Backup code must be exactly 8 characters')
      .regex(/^[A-Z0-9]{8}$/, 'Backup code must contain only uppercase letters and numbers')
      .optional(),

    /**
     * Method ID to disable (optional, disables all if not provided)
     */
    methodId: z.string().uuid('Invalid method ID format').optional(),
  })
  .refine((data) => data.code || data.backupCode, {
    message: 'Either MFA code or backup code is required',
    path: ['code'],
  });

/**
 * Generate backup codes schema
 * Used when generating new backup codes
 */
export const GenerateBackupCodesSchema = z.object({
  /**
   * Number of backup codes to generate
   * - Default: 10
   * - Minimum: 5
   * - Maximum: 20
   */
  count: z
    .number()
    .int()
    .min(5, 'Must generate at least 5 backup codes')
    .max(20, 'Cannot generate more than 20 backup codes')
    .optional()
    .default(10),
});

/**
 * Verify MFA response schema
 * Response after MFA verification attempt
 */
export const VerifyMFAResponseSchema = z.object({
  /**
   * Whether verification was successful
   */
  success: z.boolean(),

  /**
   * Response message
   */
  message: z.string(),

  /**
   * Error code if verification failed
   */
  errorCode: z.string().optional(),

  /**
   * Whether MFA is now fully enabled
   */
  mfaEnabled: z.boolean().optional(),

  /**
   * Whether backup codes were used
   */
  backupCodeUsed: z.boolean().optional(),

  /**
   * Remaining backup codes count
   */
  remainingBackupCodes: z.number().int().nonnegative().optional(),

  /**
   * Whether the device was trusted
   */
  deviceTrusted: z.boolean().optional(),
});

/**
 * MFA status response schema
 * Current MFA status for a user
 */
export const MFAStatusResponseSchema = z.object({
  /**
   * Whether MFA is enabled
   */
  enabled: z.boolean(),

  /**
   * List of active MFA methods
   */
  methods: z.array(
    z.object({
      id: z.string().uuid(),
      type: z.enum(['totp', 'sms', 'email', 'backup_codes']),
      isActive: z.boolean(),
      isPrimary: z.boolean(),
      name: z.string().optional(),
      phoneNumber: z.string().optional(),
      email: z.string().email().optional(),
      addedAt: z.date(),
      lastUsedAt: z.date().optional(),
    })
  ),

  /**
   * Number of remaining backup codes
   */
  backupCodesRemaining: z.number().int().nonnegative(),

  /**
   * Whether MFA is required for this user
   */
  mfaRequired: z.boolean(),

  /**
   * Current status of MFA
   */
  status: z.enum(['PENDING', 'ENABLED', 'DISABLED', 'LOCKED']),

  /**
   * TOTP secret for setup (if enabling)
   */
  totpSecret: z.string().optional(),

  /**
   * TOTP QR code URL (if enabling)
   */
  qrCodeUrl: z.string().url().optional(),
});

/**
 * Generate backup codes response schema
 * Response after generating backup codes
 */
export const GenerateBackupCodesResponseSchema = z.object({
  /**
   * Whether generation was successful
   */
  success: z.boolean(),

  /**
   * Generated backup codes
   */
  backupCodes: z.array(z.string().length(8)),

  /**
   * Response message
   */
  message: z.string(),

  /**
   * Error code if generation failed
   */
  errorCode: z.string().optional(),
});

/**
 * Disable MFA response schema
 * Response after disabling MFA
 */
export const DisableMFAResponseSchema = z.object({
  /**
   * Whether disabling was successful
   */
  success: z.boolean(),

  /**
   * Response message
   */
  message: z.string(),

  /**
   * Error code if disabling failed
   */
  errorCode: z.string().optional(),
});

/**
 * MFA challenge request schema
 * Used when initiating an MFA challenge
 */
export const MFAChallengeRequestSchema = z.object({
  /**
   * Type of MFA challenge
   */
  type: z.enum(['totp', 'sms', 'email', 'any']).default('any'),

  /**
   * Method ID if specific method is required
   */
  methodId: z.string().uuid('Invalid method ID format').optional(),

  /**
   * Whether to require backup codes
   */
  requireBackupCodes: z.boolean().optional().default(false),
});

/**
 * MFA challenge response schema
 * Response when initiating an MFA challenge
 */
export const MFAChallengeResponseSchema = z.object({
  /**
   * Whether the challenge was initiated
   */
  success: z.boolean(),

  /**
   * Challenge ID for tracking
   */
  challengeId: z.string().uuid().optional(),

  /**
   * Type of MFA method to use
   */
  methodType: z.enum(['totp', 'sms', 'email', 'backup_codes']).optional(),

  /**
   * Method ID to use
   */
  methodId: z.string().uuid().optional(),

  /**
   * Message for the user
   */
  message: z.string(),

  /**
   * Error code if challenge failed
   */
  errorCode: z.string().optional(),
});

/**
 * MFA trust device schema
 * Used when trusting a device for MFA
 */
export const MFATrustDeviceSchema = z.object({
  /**
   * Device ID to trust
   */
  deviceId: z.string().uuid('Invalid device ID format'),

  /**
   * Trust duration in days
   * - Default: 30
   * - Minimum: 1
   * - Maximum: 365
   */
  durationDays: z
    .number()
    .int()
    .min(1, 'Trust duration must be at least 1 day')
    .max(365, 'Trust duration cannot exceed 365 days')
    .optional()
    .default(30),
});

/**
 * MFA recovery request schema
 * Used when recovering from MFA lockout
 */
export const MFARecoveryRequestSchema = z.object({
  /**
   * Backup code for recovery
   */
  backupCode: z
    .string()
    .length(8, 'Backup code must be exactly 8 characters')
    .regex(/^[A-Z0-9]{8}$/, 'Backup code must contain only uppercase letters and numbers'),

  /**
   * User ID for recovery
   */
  userId: z.string().uuid('Invalid user ID format'),
});

/**
 * MFA recovery response schema
 * Response after MFA recovery
 */
export const MFARecoveryResponseSchema = z.object({
  /**
   * Whether recovery was successful
   */
  success: z.boolean(),

  /**
   * Response message
   */
  message: z.string(),

  /**
   * Error code if recovery failed
   */
  errorCode: z.string().optional(),

  /**
   * Whether recovery was temporary
   */
  temporaryRecovery: z.boolean().optional(),

  /**
   * New backup codes if recovery was successful
   */
  newBackupCodes: z.array(z.string().length(8)).optional(),
});

/**
 * MFA lock status schema
 * Current lock status of MFA
 */
export const MFALockStatusSchema = z.object({
  /**
   * Whether MFA is locked
   */
  isLocked: z.boolean(),

  /**
   * Number of failed attempts
   */
  failedAttempts: z.number().int().nonnegative(),

  /**
   * Max allowed attempts before lock
   */
  maxAttempts: z.number().int().positive(),

  /**
   * Lock expiry timestamp
   */
  expiresAt: z.date().optional(),

  /**
   * Time remaining in seconds
   */
  remainingSeconds: z.number().int().nonnegative().optional(),
});

