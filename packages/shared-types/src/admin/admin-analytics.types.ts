/**
 * Admin Analytics Types
 * Analytics and reporting definitions
 */

import { BaseEntity, ID, Timestamp, Nullable, JsonObject } from '../common/core-primitives.types';

/**
 * Analytics metric type
 */
export type AdminAnalyticsMetricType =
  'count' | 'sum' | 'average' | 'min' | 'max' | 'percentage' | 'rate' | 'ratio' | 'trend';

/**
 * Analytics time granularity
 */
export type AdminAnalyticsGranularity =
  'minute' | 'hour' | 'day' | 'week' | 'month' | 'quarter' | 'year';

/**
 * Analytics data source
 */
export type AdminAnalyticsSource =
  'database' | 'cache' | 'event_stream' | 'log' | 'audit' | 'api' | 'external';

