/**
 * Create analytics metric
 */
export function createAdminAnalyticsMetric(
  data: AdminAnalyticsMetricCreateData
): AdminAnalyticsMetric {
  const now = new Date();
  return {
    id: `metric_${Date.now()}_${Math.random().toString(36).substring(2, 7)}` as ID,
    name: data.name,
    value: data.value,
    type: data.type,
    timestamp: data.timestamp || now,
    granularity: data.granularity,
    source: data.source,
    dimension: data.dimension || null,
    dimensionValue: data.dimensionValue || null,
    metadata: data.metadata || null,
    isValidated: false,
    createdAt: now,
    updatedAt: now,
    deletedAt: null,
  };
}

/**
 * Calculate metric summary
 */
export function calculateAdminAnalyticsSummary(
  metrics: AdminAnalyticsMetric[]
): AdminAnalyticsResult['summary'] {
  if (!metrics.length) {
    return { total: 0, average: 0, min: 0, max: 0, count: 0 };
  }
  const values = metrics.map((m) => m.value);
  const total = values.reduce((a, b) => a + b, 0);
  return {
    total,
    average: total / values.length,
    min: Math.min(...values),
    max: Math.max(...values),
    count: values.length,
  };
}

