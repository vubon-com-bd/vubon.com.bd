/**
 * Multi-Factor Authentication (MFA) type definitions for the monorepo
 * All MFA types are centralized here for consistent usage across packages
 */

/**
 * MFA status types
 * Represents the current status of MFA for a user
 */
export type MFAStatus = 'PENDING' | 'ENABLED' | 'DISABLED' | 'LOCKED';

/**
 * MFA type types
 * Represents the supported MFA methods
 */
export type MFAType = 'TOTP' | 'SMS' | 'EMAIL' | 'BACKUP_CODE';

/**
 * MFA interface
 * Represents an MFA configuration for a user
 */
export interface MFA {
  /** Unique identifier for the MFA record */
  id: string;
  /** User ID associated with the MFA */
  userId: string;
  /** Type of MFA method */
  type: MFAType;
  /** Secret key for TOTP or other methods */
  secret: string;
  /** Current status of MFA */
  status: MFAStatus;
  /** Backup codes for account recovery */
  backupCodes: string[];
  /** Timestamp when MFA was verified */
  verifiedAt: Date | null;
  /** Timestamp when MFA was created */
  createdAt: Date;
  /** Timestamp when MFA was last updated */
  updatedAt: Date;
}

/**
 * MFA method interface
 * Represents a single MFA method for a user
 */
export interface MFAMethod {
  /** Unique identifier for the method */
  id: string;
  /** Type of MFA method */
  type: MFAType;
  /** Whether the method is active */
  isActive: boolean;
  /** Whether the method is the primary method */
  isPrimary: boolean;
  /** Friendly name for the method */
  name?: string;
  /** Phone number for SMS (if applicable) */
  phoneNumber?: string;
  /** Email address for email (if applicable) */
  email?: string;
  /** Timestamp when the method was added */
  addedAt: Date;
  /** Timestamp when the method was last used */
  lastUsedAt?: Date;
}

/**
 * Enable MFA request interface
 * Used when enabling MFA for a user
 */
export interface EnableMFARequest {
  /** Type of MFA to enable */
  type: MFAType;
  /** Phone number for SMS (required if type is SMS) */
  phoneNumber?: string;
  /** Email address for email (required if type is EMAIL) */
  email?: string;
  /** TOTP secret (generated by server) */
  secret?: string;
}

/**
 * Verify MFA request interface
 * Used when verifying an MFA code
 */
export interface VerifyMFARequest {
  /** MFA code to verify */
  code: string;
  /** Method ID for specific method (optional) */
  methodId?: string;
  /** Type of MFA method (optional) */
  type?: MFAType;
}

/**
 * Verify MFA response interface
 * Response after MFA verification attempt
 */
export interface VerifyMFAResponse {
  /** Whether verification was successful */
  success: boolean;
  /** Response message */
  message: string;
  /** Error code if verification failed */
  errorCode?: string;
  /** Whether MFA is now fully enabled */
  mfaEnabled?: boolean;
  /** Whether backup codes were used */
  backupCodeUsed?: boolean;
  /** Remaining backup codes count */
  remainingBackupCodes?: number;
}

/**
 * MFA status response interface
 * Current MFA status for a user
 */
export interface MFAStatusResponse {
  /** Whether MFA is enabled */
  enabled: boolean;
  /** List of active MFA methods */
  methods: MFAMethod[];
  /** Number of remaining backup codes */
  backupCodesRemaining: number;
  /** Whether MFA is required for this user */
  mfaRequired: boolean;
  /** Current status of MFA */
  status: MFAStatus;
}

/**
 * Disable MFA request interface
 * Used when disabling MFA for a user
 */
export interface DisableMFARequest {
  /** MFA code for verification (required) */
  code: string;
  /** Method ID to disable (optional, disables all if not provided) */
  methodId?: string;
}

/**
 * Disable MFA response interface
 * Response after disabling MFA
 */
export interface DisableMFAResponse {
  /** Whether disabling was successful */
  success: boolean;
  /** Response message */
  message: string;
  /** Error code if disabling failed */
  errorCode?: string;
}

/**
 * Generate backup codes request interface
 * Used when generating new backup codes
 */
export interface GenerateBackupCodesRequest {
  /** Number of backup codes to generate */
  count?: number;
}

/**
 * Generate backup codes response interface
 * Response after generating backup codes
 */
export interface GenerateBackupCodesResponse {
  /** Whether generation was successful */
  success: boolean;
  /** Generated backup codes */
  backupCodes: string[];
  /** Response message */
  message: string;
  /** Error code if generation failed */
  errorCode?: string;
}

/**
 * MFA configuration interface
 * Configuration for MFA system
 */
export interface MFAConfig {
  /** Whether MFA is enabled globally */
  mfaEnabled: boolean;
  /** Whether MFA is required for all users */
  requiredForAll: boolean;
  /** Whether MFA is required for admin users */
  requiredForAdmin: boolean;
  /** Supported MFA methods */
  supportedMethods: MFAType[];
  /** TOTP configuration */
  totpConfig: {
    /** TOTP issuer name */
    issuer: string;
    /** TOTP algorithm */
    algorithm: 'SHA1' | 'SHA256' | 'SHA512';
    /** Number of digits in TOTP code */
    digits: number;
    /** Time period in seconds */
    period: number;
    /** Secret length in bytes */
    secretLength: number;
    /** Verification window */
    window: number;
  };
  /** Backup codes configuration */
  backupCodesConfig: {
    /** Number of backup codes to generate */
    count: number;
    /** Length of each backup code */
    length: number;
    /** Character set for backup codes */
    charset: string;
  };
  /** SMS configuration */
  smsConfig: {
    /** Whether SMS MFA is enabled */
    enabled: boolean;
    /** SMS provider */
    provider: string;
  };
  /** Email configuration */
  emailConfig: {
    /** Whether Email MFA is enabled */
    enabled: boolean;
  };
}

/**
 * MFA verification attempt interface
 * Represents a single MFA verification attempt
 */
export interface MFAVerificationAttempt {
  /** Unique identifier for the attempt */
  id: string;
  /** User ID */
  userId: string;
  /** Type of MFA method used */
  methodType: MFAType;
  /** Method ID if applicable */
  methodId?: string;
  /** Whether the attempt was successful */
  success: boolean;
  /** Failure reason if attempt failed */
  failureReason?: string;
  /** IP address of the client */
  ipAddress: string;
  /** User agent of the client */
  userAgent: string;
  /** Timestamp of the attempt */
  timestamp: Date;
}

/**
 * MFA event interface
 * Used for MFA-related events
 */
export interface MFAEvent {
  /** Type of MFA event */
  type:
    | 'ENABLED'
    | 'DISABLED'
    | 'VERIFIED'
    | 'FAILED'
    | 'LOCKED'
    | 'UNLOCKED'
    | 'BACKUP_USED'
    | 'BACKUP_GENERATED';
  /** User ID */
  userId: string;
  /** Type of MFA method */
  methodType?: MFAType;
  /** Additional data */
  data: {
    success?: boolean;
    error?: string;
    backupCodesRemaining?: number;
    metadata?: Record<string, unknown>;
  };
  /** Timestamp of the event */
  timestamp: Date;
}

/**
 * MFA challenge request interface
 * Used when initiating an MFA challenge
 */
export interface MFAChallengeRequest {
  /** Type of MFA challenge */
  type: 'TOTP' | 'SMS' | 'EMAIL' | 'ANY';
  /** Method ID if specific method is required */
  methodId?: string;
  /** Whether to require backup codes */
  requireBackupCodes?: boolean;
}

/**
 * MFA challenge response interface
 * Response when initiating an MFA challenge
 */
export interface MFAChallengeResponse {
  /** Whether the challenge was initiated */
  success: boolean;
  /** Challenge ID for tracking */
  challengeId?: string;
  /** Type of MFA method to use */
  methodType?: MFAType;
  /** Method ID to use */
  methodId?: string;
  /** Message for the user */
  message: string;
  /** Error code if challenge failed */
  errorCode?: string;
}

/**
 * MFA recovery request interface
 * Used when recovering from MFA lockout
 */
export interface MFARecoveryRequest {
  /** Backup code for recovery */
  backupCode: string;
  /** User ID for recovery */
  userId: string;
}

/**
 * MFA recovery response interface
 * Response after MFA recovery
 */
export interface MFARecoveryResponse {
  /** Whether recovery was successful */
  success: boolean;
  /** Response message */
  message: string;
  /** Error code if recovery failed */
  errorCode?: string;
  /** Whether recovery was temporary */
  temporaryRecovery?: boolean;
  /** New backup codes if recovery was successful */
  newBackupCodes?: string[];
}

/**
 * MFA lock status interface
 * Current lock status of MFA
 */
export interface MFALockStatus {
  /** Whether MFA is locked */
  isLocked: boolean;
  /** Number of failed attempts */
  failedAttempts: number;
  /** Max allowed attempts before lock */
  maxAttempts: number;
  /** Lock expiry timestamp */
  expiresAt?: Date;
  /** Time remaining in seconds */
  remainingSeconds?: number;
}

/**
 * MFA trust device request interface
 * Used when trusting a device for MFA
 */
export interface MFATrustDeviceRequest {
  /** Device ID to trust */
  deviceId: string;
  /** Trust duration in days */
  durationDays?: number;
}

/**
 * MFA trust device response interface
 * Response after trusting a device
 */
export interface MFATrustDeviceResponse {
  /** Whether device was trusted */
  success: boolean;
  /** Trust expiry timestamp */
  expiresAt?: Date;
  /** Response message */
  message: string;
  /** Error code if trust failed */
  errorCode?: string;
}

/**
 * MFA method status interface
 * Status of a specific MFA method
 */
export interface MFAMethodStatus {
  /** Method type */
  type: MFAType;
  /** Whether the method is active */
  isActive: boolean;
  /** Whether the method is verified */
  isVerified: boolean;
  /** When the method was added */
  addedAt?: Date;
  /** When the method was last used */
  lastUsedAt?: Date;
  /** Additional metadata */
  metadata?: Record<string, unknown>;
}
